def daily_quote(offset: int = 0) -> str:
    """按台北日期輪播的大師警語；offset 讓早晚推播取不同條。"""
    index = (datetime.now(_TAIPEI_TZ).date().toordinal() + offset) % len(QUOTES)
    return f"💬 {QUOTES[index]}"
